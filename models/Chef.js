const mongoose = require('mongoose');

const chefSchema = new mongoose.Schema({
  fullname: {
    type: String,
    required: true
  },
  rank: {
    type: String,
    required: true
  },
  description: {
    type: String,
    required: true
  },
  image: {
    type: String,
    default: null
  },
  nationality: {
    type: String,
    required: true
  },
  createdAt: {
    type: Date,
    default: Date.now
  },
  updatedAt: {
    type: Date,
    default: Date.now
  }
});

module.exports = mongoose.model('Chef', chefSchema);
